def seed_missions():
    print("=" * 60)
    print("PROOF — REAL-WORLD ENGINEERING MISSIONS SEEDER")
    print("=" * 60)
    print(f"Total curated missions ready to seed: {len(MISSIONS)}")

    # Safety Assertions
    assert len(MISSIONS) == 100, f"Expected exactly 100 missions, got {len(MISSIONS)}"
    
    slugs = [m["slug"] for m in MISSIONS]
    assert len(slugs) == len(set(slugs)), "Duplicate slugs detected in mission catalog!"

    # Verify domain distribution
    domain_counts = {}
    for m in MISSIONS:
        d = m["domain"]
        domain_counts[d] = domain_counts.get(d, 0) + 1

    print("\nDomain Distribution:")
    for d, count in sorted(domain_counts.items()):
        print(f"  - {d}: {count} missions")
        assert count == 10, f"Domain {d} does not have exactly 10 missions! (has {count})"

    print("\nConnecting to Supabase PostgreSQL database...")
    db = SessionLocal()
    try:
        inserted_count = 0
        updated_count = 0

        for m_data in MISSIONS:
            slug = m_data["slug"]
            existing = db.query(Challenge).filter(Challenge.slug == slug).first()

            if existing:
                # Update existing mission with full real-world attributes
                existing.title = m_data["title"]
                existing.problem_statement = m_data["problem_statement"]
                existing.real_world_context = m_data["real_world_context"]
                existing.affected_users = m_data["affected_users"]
                existing.domain = m_data["domain"]
                existing.subdomain = m_data["subdomain"]
                existing.difficulty = m_data["difficulty"]
                existing.estimated_time = m_data["estimated_time"]
                existing.skills_required = m_data["skills_required"]
                existing.suggested_technologies = m_data["suggested_technologies"]
                existing.constraints = m_data["constraints"]
                existing.expected_outcome = m_data["expected_outcome"]
                existing.evaluation_criteria = m_data["evaluation_criteria"]
                existing.impact_description = m_data["impact_description"]
                existing.category = m_data["domain"]
                existing.skills = m_data["skills_required"]
                existing.description = m_data["real_world_context"]
                existing.expected_output = m_data["expected_outcome"]
                existing.challenge_type = "MISSION"
                existing.status = "ACTIVE"
                updated_count += 1
            else:
                # Create brand new mission
                new_mission = Challenge(
                    title=m_data["title"],
                    slug=m_data["slug"],
                    problem_statement=m_data["problem_statement"],
                    real_world_context=m_data["real_world_context"],
                    affected_users=m_data["affected_users"],
                    domain=m_data["domain"],
                    subdomain=m_data["subdomain"],
                    difficulty=m_data["difficulty"],
                    estimated_time=m_data["estimated_time"],
                    skills_required=m_data["skills_required"],
                    suggested_technologies=m_data["suggested_technologies"],
                    constraints=m_data["constraints"],
                    expected_outcome=m_data["expected_outcome"],
                    evaluation_criteria=m_data["evaluation_criteria"],
                    impact_description=m_data["impact_description"],
                    category=m_data["domain"],
                    skills=m_data["skills_required"],
                    description=m_data["real_world_context"],
                    expected_output=m_data["expected_outcome"],
                    estimated_hours=m_data["estimated_time"],
                    challenge_type="MISSION",
                    status="ACTIVE"
                )
                db.add(new_mission)
                inserted_count += 1

        db.commit()
        print(f"\nSeeding complete: {inserted_count} new missions inserted, {updated_count} updated.")

        # Total verification
        total_in_db = db.query(Challenge).count()
        print(f"Total challenges/missions in Supabase PostgreSQL: {total_in_db} (Existing: 8 + New: {len(MISSIONS)} = {8 + len(MISSIONS)})")
        assert total_in_db >= 100, f"Expected at least 100 challenges, got {total_in_db}"

    except Exception as e:
        db.rollback()
        print(f"Error during mission seeding: {e}")
        raise e
    finally:
        db.close()

if __name__ == "__main__":
    seed_missions()
